#define 2 functions: two_sum and three_sum
#two_sum: def two_sum(value_1, value_2)

def two_sum(value_1, value_2):
    sum = value_1 + value_2
    print(sum)

#three_sum: take 3 params, print sum

def three_sum(v_1, v_2, v_3):
    sum = v_1 + v_2 + v_3
    print(sum)

two_sum(7, 10)
three_sum(3,5,8)

